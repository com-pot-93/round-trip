from src.llm_connect.ask_open_ai import ask_gpt
from src.general import check_metric
from text_evaluation.text_similarity import get_cosine, sts_bert, split_and_clean, get_simple_kpis, align_sentences, calculate_precision_recall, sequence_similarity
import sys
sys.path.append("model_evaluation")
sys.path.append("model_evaluation/evaluation")
from bpmn_schema_helper import BPMNProcessor
import bpmn_similarity
import json
import os
import re
import csv
import pandas as pd
from datetime import datetime

# set default values
processor = BPMNProcessor()

# path to the original process models (json)
orig_models = "data/pet/ground_json"
# path to the original process descriptions (txt)
orig_desc = "data/pet/process_descriptions"
# path to the main direcroty where generated files should be saved
main_directory = "experiment/pipe1"
# temperature
temp1 = 1.5     #temp1 > temp2
temp2 = 0.5
# number of iterations in the pipeline
iterations = 3

# autogenerated variables requred fot the pipeline
temp = "{}_{}".format(temp1,temp2)
sub_dir1 = os.path.join(temp,"pd")
sub_dir2 = os.path.join(temp,"pm")
output1 = []
output2 = []
excel_name = "evaluation_overall.xlsx"
excel_file = os.path.join(main_directory,temp,excel_name)

# compare generated artefacts with the original ones
for i in range(1,4):
    print("----------{}----------".format(i))
    gen_desc =  os.path.join(main_directory,sub_dir1,str(i))
    gen_mods =  os.path.join(main_directory,sub_dir2,str(i))

    # compare original process description with generated process description
    print("Comapare process descriptions:")
    for path, folders, files in os.walk(gen_desc):
        for file_name in files:
            print("-------{}--------".format(file_name))
            orig_path = os.path.join(orig_desc, file_name)
            orig = open(orig_path,'r').read()
            f = os.path.join(path, file_name)
            gen = open(f,'r').read()
            sim = sts_bert(orig,gen)

            # split into sentences
            list1 = split_and_clean(orig)
            list2 = split_and_clean(gen)
            kpis = get_simple_kpis(list1,list2)

            # sequence similarity
            adjusted_list2 = align_sentences(list1, list2, threshold=0.8)
            sequence_sim = sequence_similarity(list1, adjusted_list2)

            # overall similarity
            other_kpis = calculate_precision_recall(list1, adjusted_list2)
            overall_sim = 0.5 * sim + 0.5 * sequence_sim

            result = {'round':i,'example': file_name, 'similarity': sim, 'recall': kpis[0], 'precision': kpis[1], 'sequence_similarity': sequence_sim, 'recall2': other_kpis[1], 'precision2': other_kpis[0], 'overall_sim': overall_sim}
            output1.append(result)

    # compare original process model with the generated ones
    print("Compare process models:")
    for path, folders, files in os.walk(gen_mods):
        for file_name in files:
            print("-------{}--------".format(file_name))
            orig_path = os.path.join(orig_models, file_name)
            with open(orig_path, "r") as infile:
                orig = json.load(infile)
                orig = json.dumps(orig)
            f = os.path.join(path, file_name)
            with open(f, "r") as infile:
                gen = json.load(infile)
                # gen = add_keys(gen)
                gen = json.dumps(gen)
            sim = check_metric(bpmn_similarity.calculate_similarity_scores,json.loads(orig), json.loads(gen), similarity_threshold=0.99)
            recall = check_metric(bpmn_similarity.calculate_similarity_scores,json.loads(orig), json.loads(gen), method="recall",  similarity_threshold=0.99)
            precision = check_metric(bpmn_similarity.calculate_similarity_scores,json.loads(orig), json.loads(gen), method="precision", similarity_threshold=0.99)
            result = {'round':i,'example': file_name, 'similarity': sim[1], 'recall': recall[1], 'precision': precision[1]}
            output2.append(result)

# save evaluation data to excel
output_frame1 = pd.DataFrame.from_dict(output1)
average_metrics = output_frame1.groupby('example').mean()

with pd.ExcelWriter(excel_file) as writer:
    output_frame1.to_excel(writer, sheet_name="t2t", index=False)
    average_metrics.to_excel(writer, sheet_name="t2t-aver", index=True)

output_frame2 = pd.DataFrame.from_dict(output2)
average_metrics = output_frame2.groupby('example').mean()

with pd.ExcelWriter(excel_file,mode='a',if_sheet_exists='replace') as writer:
    output_frame2.to_excel(writer, sheet_name="m2m", index=False)
    average_metrics.to_excel(writer, sheet_name="m2m-aver", index=True)

